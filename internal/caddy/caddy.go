package caddy

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/value-quest/igor/internal/config"
	"github.com/value-quest/igor/internal/launchd"
	"github.com/value-quest/igor/internal/registry"
	"github.com/value-quest/igor/internal/runner"
	"github.com/value-quest/igor/internal/runtime"
)

type Manager struct {
	cfg      *config.Config
	run      runner.Runner
	runtimes *runtime.Manager
	launchd  *launchd.Manager
}

func New(cfg *config.Config, run runner.Runner, runtimes *runtime.Manager, ld *launchd.Manager) *Manager {
	return &Manager{cfg: cfg, run: run, runtimes: runtimes, launchd: ld}
}

func (m *Manager) ProxyBin() (string, error) {
	v, err := m.runtimes.NewestPHP()
	if err != nil {
		return "", err
	}
	return filepath.Join(m.cfg.PHPBin(v), "frankenphp"), nil
}

func (m *Manager) EnsureDefaultIni() error {
	if err := m.cfg.EnsureDir(m.cfg.IniDir); err != nil {
		return err
	}
	iniFile := filepath.Join(m.cfg.IniDir, "99-igor.ini")
	if _, err := os.Stat(iniFile); err == nil {
		return nil
	}
	content := `; Shared dev settings for all sites and the CLI (via PHP_INI_SCAN_DIR)
memory_limit = 512M
upload_max_filesize = 64M
post_max_size = 64M
max_execution_time = 120
display_errors = On
error_reporting = E_ALL
date.timezone = Europe/Zurich
opcache.enable = 1
opcache.enable_cli = 0
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
`
	return os.WriteFile(iniFile, []byte(content), 0o644)
}

func (m *Manager) EnsureFrontCaddyfile() error {
	if err := m.cfg.EnsureDir(m.cfg.IgorHome); err != nil {
		return err
	}
	if err := m.cfg.EnsureDir(m.cfg.SitesDir); err != nil {
		return err
	}
	if _, err := os.Stat(m.cfg.Caddyfile); err == nil {
		return nil
	}
	content := fmt.Sprintf(`{
	local_certs
	admin localhost:2019
	# Listens on all interfaces, so sites are reachable from your LAN unless
	# the macOS firewall blocks it. Binding only 127.0.0.1 to ports 80/443
	# needs root on macOS.
}

import %s/*.caddy
`, m.cfg.SitesDir)
	return os.WriteFile(m.cfg.Caddyfile, []byte(content), 0o644)
}

func (m *Manager) WriteProxyRunner() (string, error) {
	if err := m.cfg.EnsureDir(m.cfg.ShimDir); err != nil {
		return "", err
	}
	file := filepath.Join(m.cfg.ShimDir, "igor-proxy")
	content := `#!/bin/bash
# igor: runs the front proxy using the newest installed FrankenPHP runtime
set -eu
IGOR_HOME="${IGOR_HOME:-$HOME/.igor}"
PHP_ROOT="${IGOR_PHP_ROOT:-$HOME/frankenphp}"
v=$(ls -d "$PHP_ROOT"/php8.* 2>/dev/null | sed 's|.*/php||' | grep -E '^[0-9]+\.[0-9]+$' |
    sort -t. -k1,1nr -k2,2nr | head -1 || true)
if [ -z "$v" ] || [ ! -x "$PHP_ROOT/php$v/bin/frankenphp" ]; then
    echo "igor-proxy: no FrankenPHP runtime installed in $PHP_ROOT" >&2
    exit 1
fi
bin="$PHP_ROOT/php$v/bin"
export PATH="$bin:/usr/bin:/bin:/usr/sbin:/sbin"
exec "$bin/frankenphp" run --config "$IGOR_HOME/Caddyfile" --adapter caddyfile
`
	if existing, err := os.ReadFile(file); err != nil || string(existing) != content {
		tmp := file + ".tmp"
		if err := os.WriteFile(tmp, []byte(content), 0o755); err != nil {
			return "", err
		}
		if err := os.Rename(tmp, file); err != nil {
			return "", err
		}
	}
	return file, nil
}

func (m *Manager) WriteSiteRunner() (string, error) {
	if err := m.cfg.EnsureDir(m.cfg.ShimDir); err != nil {
		return "", err
	}
	file := filepath.Join(m.cfg.ShimDir, "igor-site")
	content := `#!/bin/bash
# igor: runs one site's FrankenPHP backend using the PHP version from sites.tsv
set -eu
name="$1"
IGOR_HOME="${IGOR_HOME:-$HOME/.igor}"
PHP_ROOT="${IGOR_PHP_ROOT:-$HOME/frankenphp}"
php=$(awk -F'\t' -v n="$name" '$1==n {print $4; exit}' "$IGOR_HOME/sites.tsv")
if [ -z "$php" ]; then
    echo "igor-site: site '$name' not found in $IGOR_HOME/sites.tsv" >&2
    exit 1
fi
bin="$PHP_ROOT/php$php/bin"
export PATH="$bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
exec "$bin/frankenphp" run --config "$IGOR_HOME/backends/$name.Caddyfile" --adapter caddyfile
`
	if existing, err := os.ReadFile(file); err != nil || string(existing) != content {
		tmp := file + ".tmp"
		if err := os.WriteFile(tmp, []byte(content), 0o755); err != nil {
			return "", err
		}
		if err := os.Rename(tmp, file); err != nil {
			return "", err
		}
	}
	return file, nil
}

func (m *Manager) WriteProxyPlist() (bool, error) {
	if _, err := m.runtimes.NewestPHP(); err != nil {
		return false, err
	}
	runnerPath, err := m.WriteProxyRunner()
	if err != nil {
		return false, err
	}
	return m.launchd.WritePlist(
		"proxy",
		m.cfg.IgorHome,
		"/usr/bin:/bin:/usr/sbin:/sbin",
		[]string{runnerPath},
		[]launchd.EnvVar{
			{Key: "IGOR_HOME", Value: m.cfg.IgorHome},
			{Key: "IGOR_PHP_ROOT", Value: m.cfg.PHPRoot},
		},
		nil,
	)
}

func (m *Manager) WriteBackend(entry registry.Entry) (bool, error) {
	if err := m.cfg.EnsureDir(m.cfg.BackendsDir); err != nil {
		return false, err
	}
	content := fmt.Sprintf(`# generated by igor - changes are overwritten
{
	frankenphp
	auto_https off
	admin off
	persist_config off
}

http://:%s {
	bind 127.0.0.1
	root * "%s"
	php_server {
		env HTTPS on
	}
}
`, entry.Port, entry.AbsoluteDocroot())

	file := m.cfg.BackendCaddyfilePath(entry.Name)
	if existing, err := os.ReadFile(file); err == nil && string(existing) == content {
		return false, nil
	}
	tmp := file + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, file)
}

func (m *Manager) WriteSite(entry registry.Entry) (bool, error) {
	backendChanged, err := m.WriteBackend(entry)
	if err != nil {
		return false, err
	}
	runnerPath, err := m.WriteSiteRunner()
	if err != nil {
		return false, err
	}
	plistChanged, err := m.launchd.WritePlist(
		entry.Name,
		entry.Dir,
		"/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin",
		[]string{runnerPath, entry.Name},
		[]launchd.EnvVar{
			{Key: "IGOR_HOME", Value: m.cfg.IgorHome},
			{Key: "IGOR_PHP_ROOT", Value: m.cfg.PHPRoot},
		},
		nil,
	)
	if err != nil {
		return false, err
	}
	return backendChanged || plistChanged, nil
}

func (m *Manager) WriteRoute(name, port string) error {
	if err := m.cfg.EnsureDir(m.cfg.SitesDir); err != nil {
		return err
	}
	content := fmt.Sprintf("%s.%s {\n\treverse_proxy 127.0.0.1:%s\n}\n", name, m.cfg.TLD, port)
	return os.WriteFile(m.cfg.SiteRoutePath(name), []byte(content), 0o644)
}

func (m *Manager) RemoveRoute(name string) {
	_ = os.Remove(m.cfg.SiteRoutePath(name))
}

func (m *Manager) ReloadProxy() (bool, error) {
	if !m.launchd.IsRunning("proxy") {
		return false, nil
	}
	bin, err := m.ProxyBin()
	if err != nil {
		return false, err
	}
	if !m.run.Run(bin, "reload", "--config", m.cfg.Caddyfile, "--adapter", "caddyfile").OK() {
		return false, fmt.Errorf("proxy reload failed - check: igor logs proxy")
	}
	return true, nil
}
