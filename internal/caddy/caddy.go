package caddy

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/value-quest/igor/internal/config"
	"github.com/value-quest/igor/internal/registry"
	"github.com/value-quest/igor/internal/runner"
	"github.com/value-quest/igor/internal/runtime"
	"github.com/value-quest/igor/internal/supervisor"
)

type Manager struct {
	cfg      *config.Config
	run      runner.Runner
	runtimes *runtime.Manager
	sup      supervisor.Manager
}

func New(cfg *config.Config, run runner.Runner, runtimes *runtime.Manager, sup supervisor.Manager) *Manager {
	return &Manager{cfg: cfg, run: run, runtimes: runtimes, sup: sup}
}

func (m *Manager) ProxyBin() (string, error) {
	v, err := m.runtimes.NewestPHP()
	if err != nil {
		return "", err
	}
	return filepath.Join(m.cfg.PHPBin(v), "frankenphp"), nil
}

func (m *Manager) EnsureDefaultIni() error {
	if err := m.cfg.EnsureDir(m.cfg.IniDir); err != nil {
		return err
	}
	iniFile := filepath.Join(m.cfg.IniDir, "99-igor.ini")
	if _, err := os.Stat(iniFile); err == nil {
		return nil
	}
	content := `; Shared dev settings for all sites and the CLI (via PHP_INI_SCAN_DIR)
memory_limit = 512M
upload_max_filesize = 64M
post_max_size = 64M
max_execution_time = 120
display_errors = On
error_reporting = E_ALL
date.timezone = Europe/Zurich
opcache.enable = 1
opcache.enable_cli = 0
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
`
	return os.WriteFile(iniFile, []byte(content), 0o644)
}

func (m *Manager) EnsureFrontCaddyfile() error {
	if err := m.cfg.EnsureDir(m.cfg.IgorHome); err != nil {
		return err
	}
	if err := m.cfg.EnsureDir(m.cfg.SitesDir); err != nil {
		return err
	}
	if _, err := os.Stat(m.cfg.Caddyfile); err == nil {
		return nil
	}
	content := fmt.Sprintf(`{
	local_certs
	admin localhost:2019
	# Listens on all interfaces, so sites are reachable from your LAN unless
	# the macOS firewall blocks it. Binding only 127.0.0.1 to ports 80/443
	# needs root on macOS.
}

import %s/*.caddy
`, m.cfg.SitesDir)
	return os.WriteFile(m.cfg.Caddyfile, []byte(content), 0o644)
}

func (m *Manager) WriteProxyPlist() (bool, error) {
	newest, err := m.runtimes.NewestPHP()
	if err != nil {
		return false, err
	}
	bin := m.cfg.PHPBin(newest)
	return m.sup.WriteUnit(
		"proxy",
		m.cfg.IgorHome,
		bin+":/usr/bin:/bin:/usr/sbin:/sbin",
		[]string{filepath.Join(bin, "frankenphp"), "run", "--config", m.cfg.Caddyfile, "--adapter", "caddyfile"},
		nil,
		nil,
	)
}

func (m *Manager) WriteBackend(entry registry.Entry) (bool, error) {
	if err := m.cfg.EnsureDir(m.cfg.BackendsDir); err != nil {
		return false, err
	}
	content := fmt.Sprintf(`# generated by igor - changes are overwritten
{
	frankenphp
	auto_https off
	admin off
	persist_config off
}

http://:%s {
	bind 127.0.0.1
	root * "%s"
	php_server {
		env HTTPS on
	}
}
`, entry.Port, entry.AbsoluteDocroot())

	file := m.cfg.BackendCaddyfilePath(entry.Name)
	if existing, err := os.ReadFile(file); err == nil && string(existing) == content {
		return false, nil
	}
	tmp := file + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, file)
}

func (m *Manager) WriteSite(entry registry.Entry) (bool, error) {
	backendChanged, err := m.WriteBackend(entry)
	if err != nil {
		return false, err
	}
	bin := m.cfg.PHPBin(entry.PHP)
	plistChanged, err := m.sup.WriteUnit(
		entry.Name,
		entry.Dir,
		bin+":/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin",
		[]string{filepath.Join(bin, "frankenphp"), "run", "--config", m.cfg.BackendCaddyfilePath(entry.Name), "--adapter", "caddyfile"},
		nil,
		nil,
	)
	if err != nil {
		return false, err
	}
	return backendChanged || plistChanged, nil
}

func (m *Manager) WriteRoute(name, port string) error {
	if err := m.cfg.EnsureDir(m.cfg.SitesDir); err != nil {
		return err
	}
	content := fmt.Sprintf("%s.%s {\n\treverse_proxy 127.0.0.1:%s\n}\n", name, m.cfg.TLD, port)
	return os.WriteFile(m.cfg.SiteRoutePath(name), []byte(content), 0o644)
}

func (m *Manager) RemoveRoute(name string) {
	_ = os.Remove(m.cfg.SiteRoutePath(name))
}

func (m *Manager) ReloadProxy() (bool, error) {
	if !m.sup.IsRunning("proxy") {
		return false, nil
	}
	bin, err := m.ProxyBin()
	if err != nil {
		return false, err
	}
	if !m.run.Run(bin, "reload", "--config", m.cfg.Caddyfile, "--adapter", "caddyfile").OK() {
		return false, fmt.Errorf("proxy reload failed - check: igor logs proxy")
	}
	return true, nil
}
